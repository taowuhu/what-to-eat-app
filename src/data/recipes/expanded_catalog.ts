import { Recipe, RecipeCategory, MealType, ProteinSource, RecipeDifficulty, CookingMethod, IngredientCategory } from '../../types';

// Helper function to build recipes with standard structure cleanly
export function createRecipeItem(
  id: string,
  name: string,
  category: RecipeCategory,
  mealTypes: MealType[],
  proteinSource: ProteinSource,
  tags: string[],
  timeMinutes: number,
  difficulty: RecipeDifficulty,
  summary: string,
  cookingMethod: CookingMethod,
  equipment: string[],
  ingredients: { name: string; amount: number; unit: string; category: IngredientCategory; grams?: number }[],
  steps: { stepNumber: number; title: string; action: string; durationSeconds: number; visualCue: string; tip: string }[],
  nutrition: { calories: number; protein: number; carbs: number; fat: number },
  imageUrl: string,
  dislikeTags: string[] = []
): Recipe {
  return {
    id,
    name,
    category,
    mealTypes,
    proteinSource,
    tags,
    timeMinutes,
    prepTimeMinutes: Math.max(2, Math.floor(timeMinutes * 0.3)),
    cookTimeMinutes: Math.max(3, Math.ceil(timeMinutes * 0.7)),
    difficulty,
    difficultyLevel: difficulty === '小白友好' ? 1 : difficulty === '进阶家常' ? 2 : 3,
    servings: 1,
    summary,
    cookingMethod,
    equipment,
    ingredients,
    steps: steps.map(s => ({
      ...s,
      ingredientsUsed: [],
    })),
    nutritionEstimate: nutrition,
    calories: nutrition.calories,
    protein: nutrition.protein,
    carbs: nutrition.carbs,
    fat: nutrition.fat,
    imageUrl,
    dislikeTags,
  };
}

